#!/usr/bin/env python3
"""eyedropper-grade: sample the real colours the eyedropper taps and grade them the way the picture is graded.

Each swatch is a real pixel average (9x9) from <project>/public/clean.mp4 at its point, on the frame the dropper
taps it. It goes through the look on screen at that moment (the house grade from the style pack, or a GRADES entry
already running), then through every GRADES step that starts inside this effect's window, so on every step a chip
shows exactly what the grade does to that colour. The steps are the project's own edit.GRADES entries: put one on
each word of the line ("colours", "go", "dark"), each a named look or a CSS filter, the last one ending with the line.
Writes the generated block of <project>/fx/<id>/fx.js (CHIPS, STEPS, between the two markers) and nothing else.

Run: PY fx/<id>/gen.py <project> [<id>]
  reads   <project>/edit.py (the FX entry <id>, GRADES), public/clean.mp4, style/style.json (the house grade)
  writes  <project>/fx/<id>/fx.js (the block between the markers)
<id> defaults to this script's folder name. Rerun it whenever the window, the cut, GRADES or SAMPLES change.
"""
import argparse
import ast
import importlib.util
import json
import math
import os
import re
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
FPS = 30

# The swatches, in the order the dropper taps them: (label, x, y) on the 1080x1920 frame. Keep every point out of the
# palette card (RAIL in fx.js), off the caption band (y 1300-1470) and on something that holds still for a second.
# The path reads best as a loop around the frame. Labels are plain true names of what is under the point.
SAMPLES = [("SHIRT", 700, 1240), ("WALL", 960, 1060), ("FRAME", 860, 560), ("WINDOW", 380, 330), ("HEAD", 600, 760)]
FIRST = 0.067           # s after the effect's start: the first tap
EVERY = 3               # frames between taps
BOX = 4                 # the swatch averages (2 * BOX + 1)^2 pixels around its point

BEGIN = "// ---- generated by gen.py: it rewrites the lines between these two markers ----"
END = "// ---- end of generated ----"


def load_edit(project):
    spec = importlib.util.spec_from_file_location("edit", os.path.join(project, "edit.py"))
    E = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(E)
    return E


def kit_looks():
    """the named looks (edit.GRADES names) from the kit's pipeline/build.py, read without importing it"""
    for d in (os.path.join(HERE, "..", ".."), "~/.claude/skills/video-editor", "~/.agents/skills/video-editor"):
        p = os.path.join(os.path.expanduser(d), "pipeline", "build.py")
        if os.path.exists(p):
            for node in ast.parse(open(p, encoding="utf-8").read()).body:
                if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "LOOKS" for t in node.targets):
                    return ast.literal_eval(node.value)
    return {}


def house_grade(project):
    """the grade under everything: what the last build put on screen (public/index.html), else the style pack's"""
    built = os.path.join(project, "public", "index.html")
    if os.path.exists(built):
        m = re.search(r"var COLOR = '([^']*)'", open(built, encoding="utf-8").read())
        if m:
            return m.group(1)
    home = os.path.expanduser(os.environ.get("VIDEO_EDITOR_HOME", "~/video-editor"))
    for p in (os.path.join(project, "style", "style.json"), os.path.join(home, "style", "style.json")):
        if os.path.exists(p):
            return json.load(open(p)).get("grade") or "none"
    return "none"


# ---- CSS filter functions on one sRGB colour (0-1), as the Filter Effects spec defines them
def _num(v, pct_default=1.0):
    v = v.strip()
    if not v:
        return pct_default
    return float(v[:-1]) / 100 if v.endswith("%") else float(v.replace("deg", ""))


def css_filter(rgb, css):
    v = np.array(rgb, float)
    for name, arg in re.findall(r"([a-z-]+)\(([^)]*)\)", css or ""):
        a = _num(arg)
        if name == "brightness":
            v = v * a
        elif name == "contrast":
            v = (v - 0.5) * a + 0.5
        elif name in ("saturate", "grayscale", "sepia", "hue-rotate"):
            if name == "saturate":
                s = a
                M = [[0.213 + 0.787 * s, 0.715 - 0.715 * s, 0.072 - 0.072 * s],
                     [0.213 - 0.213 * s, 0.715 + 0.285 * s, 0.072 - 0.072 * s],
                     [0.213 - 0.213 * s, 0.715 - 0.715 * s, 0.072 + 0.928 * s]]
            elif name == "grayscale":
                g = 1 - min(1, a)
                M = [[0.2126 + 0.7874 * g, 0.7152 - 0.7152 * g, 0.0722 - 0.0722 * g],
                     [0.2126 - 0.2126 * g, 0.7152 + 0.2848 * g, 0.0722 - 0.0722 * g],
                     [0.2126 - 0.2126 * g, 0.7152 - 0.7152 * g, 0.0722 + 0.9278 * g]]
            elif name == "sepia":
                g = 1 - min(1, a)
                M = [[0.393 + 0.607 * g, 0.769 - 0.769 * g, 0.189 - 0.189 * g],
                     [0.349 - 0.349 * g, 0.686 + 0.314 * g, 0.168 - 0.168 * g],
                     [0.272 - 0.272 * g, 0.534 - 0.534 * g, 0.131 + 0.869 * g]]
            else:
                c, s = math.cos(math.radians(a)), math.sin(math.radians(a))
                M = [[0.213 + c * 0.787 - s * 0.213, 0.715 - c * 0.715 - s * 0.715, 0.072 - c * 0.072 + s * 0.928],
                     [0.213 - c * 0.213 + s * 0.143, 0.715 + c * 0.285 + s * 0.140, 0.072 - c * 0.072 - s * 0.283],
                     [0.213 - c * 0.213 - s * 0.787, 0.715 - c * 0.715 + s * 0.715, 0.072 + c * 0.928 + s * 0.072]]
            v = np.array(M) @ v
        elif name == "invert":
            v = v * (1 - 2 * a) + a
        v = np.clip(v, 0, 1)
    return v


def hexc(v):
    return "#%02X%02X%02X" % tuple(int(round(x * 255)) for x in np.clip(v, 0, 1))


def grab(project, n):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", os.path.join(project, "public", "clean.mp4"),
                          "-vf", f"select=eq(n\\,{n})", "-frames:v", "1", "-f", "rawvideo", "-pix_fmt", "rgb24", "-"],
                         capture_output=True, check=True).stdout
    if len(raw) != 1920 * 1080 * 3:
        sys.exit(f"public/clean.mp4: no frame {n}")
    return np.frombuffer(raw, np.uint8).reshape(1920, 1080, 3)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("project")
    ap.add_argument("id", nargs="?", default=os.path.basename(HERE))
    args = ap.parse_args()
    project, fid = os.path.abspath(os.path.expanduser(args.project)), args.id
    E = load_edit(project)
    F = next((F for F in getattr(E, "FX", []) if F["id"] == fid), None)
    if not F:
        sys.exit(f"no FX entry with id {fid!r} in {project}/edit.py")
    A = float(F["at"])
    B = float(F["end"]) if F["end"] != "end" else json.load(open(os.path.join(project, "timeline.json")))["total"]
    looks, house = kit_looks(), house_grade(project)

    def css(look):
        return looks.get(look, look)

    grades = sorted((g for g in getattr(E, "GRADES", []) if A - 1e-6 <= g[0] < B), key=lambda g: g[0])
    if not grades:
        sys.exit(f"no GRADES entry starts inside {fid}'s window {A:.2f}-{B:.2f}: add one per word of the line, e.g.\n"
                 f'    ({A + 0.5:.2f}, {A + 0.9:.2f}, "sepia(0.03) contrast(1.10) saturate(0.72) brightness(0.84) hue-rotate(2deg)"),')
    for g in grades:
        if "(" not in css(g[2]):
            sys.exit(f"GRADES look {g[2]!r} is neither a named look nor a CSS filter")

    def look_at(t):                                    # what is on screen at t: a GRADES entry running, else the house
        on = [g for g in getattr(E, "GRADES", []) if g[0] <= t + 1e-6 and (g[1] == "end" or t < float(g[1]) - 1e-6)]
        return css(on[-1][2]) if on else house

    f0 = round((A + FIRST) * FPS)
    chips = []
    for k, (lab, x, y) in enumerate(SAMPLES):
        n = f0 + k * EVERY
        im = grab(project, n)
        raw = im[y - BOX:y + BOX + 1, x - BOX:x + BOX + 1].reshape(-1, 3).mean(axis=0) / 255.0
        seen = hexc(css_filter(raw, look_at(n / FPS)))
        steps = [hexc(css_filter(raw, css(g[2]))) for g in grades]
        chips.append(dict(lab=lab, x=x, y=y, t=round(n / FPS - A, 4), c=[seen] + steps))
        print(f"{lab:<8} {hexc(raw)} at frame {n} -> {' '.join([seen] + steps)}")

    block = "\n".join([BEGIN,
                       "var CHIPS = [   // label, the point tapped, its tap (s after A), its colour now and after each step",
                       *[f"  {json.dumps(c)}," for c in chips],
                       "];",
                       f"var STEPS = {json.dumps([round(g[0] - A, 4) for g in grades])};   "
                       "// s after A: the GRADES steps (the chips step with the picture)",
                       END])
    d = os.path.join(project, "fx", fid)
    path = os.path.join(d, "fx.js")
    if not os.path.exists(path):
        os.makedirs(d, exist_ok=True)
        js = open(os.path.join(HERE, "fx.js"), encoding="utf-8").read()
    else:
        js = open(path, encoding="utf-8").read()
    i, j = js.index(BEGIN), js.index(END) + len(END)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(js[:i] + block + js[j:])
    print(f"wrote the CHIPS / STEPS block of {path}; steps at " + ", ".join(f"{g[0]:.2f}" for g in grades)
          + f"; house grade {house!r}")


if __name__ == "__main__":
    main()
