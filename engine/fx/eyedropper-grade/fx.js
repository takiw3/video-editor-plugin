/* eyedropper-grade (layer: cam). A grade change you can read: the colours of the shot, sampled, step darker with it.
   Beat by beat:
     first tap - 0.12 s   the palette card slides in from the left, empty slots waiting; the eyedropper enters
     taps (every 3 frames from A + 0.067)   the dropper taps each real colour off the shot: a loupe ring fills with it,
                 the pipette fills, a chip flies from the point into its slot and its hex types in, 2 characters a frame
     each GRADES step (one per word: "colours", "go", "dark")   the picture steps darker and every chip and hex steps
                 with it, a notch in the card's header fills, the chips bob; grain comes up on the last step
     B - OUT     the chips drop away, the card slides off the left; the grade and the grain end with the line at B
   Reach for it on "the colours go dark", "it grades it", any grade change you want to show the numbers of.
   Supply: GRADES steps in edit.py that start inside the window, one per word, the last ending with the line (B), then
     PY fx/<id>/gen.py <project> [<id>]
   which samples the real pixels (SAMPLES in gen.py: label and point per swatch) from public/clean.mp4 on their tap
   frames and writes CHIPS / STEPS below. Rerun it whenever the window, the cut, GRADES or SAMPLES change.
   grain.png is self-made by make_grain.py.
   Sound: a click per tap, a tick per hex, a switch-off per step (each word), a whoosh-soft as the card leaves.
   Change only these constants: */
var TITLE = 'Sampled';              // the card's header
var RAIL = [40, 560];               // the card's top-left corner (px): over a calm part of the frame, off the face
var ROW = 76, HEAD = 40;            // row pitch and header height (px)
var OUT = 0.32;                     // s before B: the chips drop, then the card slides off
var GRAIN = 0.22;                   // grain strength from the last step to B (0 = none)

// ---- generated by gen.py: it rewrites the lines between these two markers ----
var CHIPS = [   // label, the point tapped, its tap (s after A), its colour now and after each step
  {"lab": "SHIRT", "x": 700, "y": 1240, "t": 0.0667, "c": ["#182431", "#131A22", "#0D1319", "#080D12"]},
  {"lab": "WALL", "x": 960, "y": 1060, "t": 0.1667, "c": ["#89847B", "#74706A", "#696660", "#615F5A"]},
  {"lab": "FRAME", "x": 860, "y": 560, "t": 0.2667, "c": ["#A37E58", "#836C53", "#75634E", "#6B5C49"]},
  {"lab": "WINDOW", "x": 380, "y": 330, "t": 0.3667, "c": ["#E6E2D5", "#C7C4BB", "#B9B7AF", "#B0AEA6"]},
  {"lab": "HEAD", "x": 600, "y": 760, "t": 0.4667, "c": ["#243442", "#1F2830", "#192027", "#141A20"]},
];
var STEPS = [0.5, 0.9, 1.3];   // s after A: the GRADES steps (the chips step with the picture)
// ---- end of generated ----

var FPS = 30;
function tok(n) { return getComputedStyle(document.documentElement).getPropertyValue(n).trim(); }
function rnd(i) { var x = Math.sin(i * 12.9898) * 43758.5453; return x - Math.floor(x); }
function fq(f) { return Math.max(0, f / FPS - 0.002); }
function hexAt(c, t) { var n = 0; STEPS.forEach(function (s) { if (t >= A + s - 0.01) n++; }); return c.c[Math.min(n, c.c.length - 1)]; }

// ---- build the card: one row per chip, one notch per step
var rows = document.getElementById('{{ID}}-rows'), notches = document.getElementById('{{ID}}-notches');
document.getElementById('{{ID}}-title').textContent = TITLE;
CHIPS.forEach(function (c, k) {
  var r = document.createElement('div');
  r.className = '{{ID}}-row';
  r.style.top = (HEAD + k * ROW) + 'px';
  r.innerHTML = '<div id="{{ID}}-slot' + k + '" class="{{ID}}-slot"></div><div id="{{ID}}-chip' + k + '" class="{{ID}}-chip"></div>' +
    '<div class="{{ID}}-hexc"><div id="{{ID}}-hex' + k + '" class="{{ID}}-hex" data-layout-allow-overlap></div></div>' +
    '<div id="{{ID}}-lab' + k + '" class="{{ID}}-lab" data-layout-allow-overlap></div>';
  rows.appendChild(r);
  document.getElementById('{{ID}}-lab' + k).textContent = c.lab;
  document.getElementById('{{ID}}-chip' + k).style.backgroundColor = c.c[0];
});
STEPS.forEach(function (s, n) {
  var i = document.createElement('i');
  i.className = '{{ID}}-notch';
  i.innerHTML = '<b id="{{ID}}-n' + n + '"></b>';
  notches.appendChild(i);
});
var rail = document.getElementById('{{ID}}-rail');
rail.style.height = (HEAD + CHIPS.length * ROW + 8) + 'px';
document.getElementById('{{ID}}-liq').setAttribute('fill', tok('--c-light'));

// ---- times
var taps = CHIPS.map(function (c) { return A + c.t; });
var t0 = taps.length ? taps[0] : A + 0.067, tLast = taps.length ? taps[taps.length - 1] : t0;
var tOut = B - OUT;

gsap.set('#{{ID}}-rail', { x: RAIL[0] - 340, y: RAIL[1] });
gsap.set('#{{ID}}-drop', { opacity: 0, x: 1120, y: 1500, transformOrigin: '24px 116px' });
gsap.set('#{{ID}}-ring', { opacity: 0, scale: 0.4, transformOrigin: '36px 36px' });
CHIPS.forEach(function (c, k) { gsap.set(['#{{ID}}-chip' + k, '#{{ID}}-lab' + k], { opacity: 0 }); });

tl.fromTo('#{{ID}}-rail', { x: RAIL[0] - 340 }, { x: RAIL[0], duration: 0.24, ease: 'power3.out', immediateRender: false }, q(Math.max(A, t0 - 0.12)));
if (CHIPS.length) {
  tl.set('#{{ID}}-drop', { opacity: 1 }, q(Math.max(A, t0 - 0.087)));
  tl.to('#{{ID}}-drop', { x: CHIPS[0].x - 24, y: CHIPS[0].y - 116, duration: 0.08, ease: 'power3.out' }, q(Math.max(A, t0 - 0.087)));
}
CHIPS.forEach(function (c, k) {
  var t = taps[k];
  if (k > 0) tl.to('#{{ID}}-drop', { x: c.x - 24, y: c.y - 116, duration: 0.066, ease: 'power2.inOut' }, q(t - 0.066));
  tl.set('#{{ID}}-ring', { x: c.x - 36, y: c.y - 36, backgroundColor: hexAt(c, t), opacity: 1 }, q(t));
  tl.fromTo('#{{ID}}-ring', { scale: 0.45 }, { scale: 1, duration: 0.1, ease: 'back.out(1.6)', immediateRender: false }, q(t));
  tl.set('#{{ID}}-liq', { attr: { fill: hexAt(c, t) } }, q(t));
  tl.fromTo('#{{ID}}-drop', { scale: 0.88 }, { scale: 1, duration: 0.1, ease: 'power2.out', immediateRender: false }, q(t));
  // the chip leaves the loupe and lands in its slot
  var sx = RAIL[0] + 16 + 28, sy = RAIL[1] + HEAD + k * ROW + 8 + 28;
  tl.set('#{{ID}}-chip' + k, { opacity: 1, backgroundColor: hexAt(c, t + 0.033) }, q(t + 0.033));
  tl.fromTo('#{{ID}}-chip' + k, { x: c.x - sx, y: c.y - sy, scale: 0.75, rotation: -12 + 24 * rnd(k) },
    { x: 0, y: 0, scale: 1, rotation: 0, duration: 0.26, ease: 'power3.inOut', immediateRender: false }, q(t + 0.033));
  var land = t + 0.3;
  tl.set('#{{ID}}-slot' + k, { opacity: 0 }, q(land));
  for (var i = 1; i <= 4; i++) {                 // the hex types in, 2 characters a frame, in whatever step it's at
    var tt = land + (i - 1) / FPS;
    tl.set('#{{ID}}-hex' + k, { textContent: hexAt(c, tt).slice(0, Math.min(7, 2 * i)) }, q(tt));
  }
  tl.set('#{{ID}}-lab' + k, { opacity: 1 }, q(land));
});
tl.to('#{{ID}}-ring', { scale: 0.4, opacity: 0, duration: 0.1, ease: 'power2.in' }, q(tLast + 0.033));
if (CHIPS.length) {
  var lc = CHIPS[CHIPS.length - 1];
  tl.to('#{{ID}}-drop', { x: lc.x - 24 + 150, y: lc.y - 116 - 210, opacity: 0, duration: 0.16, ease: 'power2.in' }, q(tLast + 0.033));
}

// the dimmer: one step per word, the chips with the picture
STEPS.forEach(function (s, n) {
  var t = A + s;
  tl.set('#{{ID}}-n' + n, { opacity: 1 }, q(t));
  CHIPS.forEach(function (c, k) {
    var after = c.c[Math.min(n + 1, c.c.length - 1)];
    if (taps[k] + 0.033 < t) tl.set('#{{ID}}-chip' + k, { backgroundColor: after }, q(t));
    if (taps[k] + 0.3 + 3 / FPS < t) tl.set('#{{ID}}-hex' + k, { textContent: after }, q(t));   // else its typing carries it
    if (taps[k] + 0.3 < t) {
      tl.to('#{{ID}}-chip' + k, { y: 5, duration: 0.05, ease: 'power2.out' }, q(t + k * 0.017));
      tl.to('#{{ID}}-chip' + k, { y: 0, duration: 0.12, ease: 'power2.out' }, q(t + k * 0.017 + 0.05));
    }
  });
});
if (STEPS.length && GRAIN > 0) {
  var fG = Math.round((A + STEPS[STEPS.length - 1]) * FPS), fB = Math.round(B * FPS);
  tl.set('#{{ID}}-grain', { opacity: GRAIN }, fq(fG));
  for (var f = fG; f < fB; f++) {
    tl.set('#{{ID}}-gt', { x: -Math.floor(rnd(f) * 512), y: -Math.floor(rnd(f + 977) * 512) }, fq(f));
  }
}

// out: the chips drop away, then the card slides off the left
CHIPS.forEach(function (c, k) {
  tl.to('#{{ID}}-chip' + k, { scale: 0, duration: 0.12, ease: 'power3.in' }, q(tOut + k * 0.02));
});
tl.to('#{{ID}}-rail', { x: RAIL[0] - 340, duration: 0.16, ease: 'power3.in' }, q(tOut + 0.1));
